// 允许手工覆盖第一条示例缺失的 dataTsv 之外，其余按 plan 整段替换
const ids = Object.keys(plan);
let changed = 0;
for (const id of ids) {
  const file = join(dir, `${id}.ts`);
  let src = readFileSync(file, 'utf8');
  const start = src.indexOf('examples: [');
  if (start < 0) throw new Error(`no examples in ${id}`);
  let i = src.indexOf('[', start);
  let depth = 0;
  let end = -1;
  let inStr = false;
  let quote = '';
  for (let j = i; j < src.length; j++) {
    const ch = src[j];
    if (inStr) {
      if (ch === '\\') { j++; continue; }
      if (ch === quote) inStr = false;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') { inStr = true; quote = ch; continue; }
    if (ch === '[') depth++;
    if (ch === ']') { depth--; if (depth === 0) { end = j; break; } }
  }
  if (end < 0) throw new Error(`unbalanced examples in ${id}`);
  const body = plan[id].map((ex) => {
    const parts = [
      `title: '${ex.title}'`,
      `scene: '${ex.scene}'`,
      `dataAnchor: '${ex.dataAnchor}'`,
      `formula: '${ex.formula}'`,
      `result: '${ex.result}'`,
      `explanation: '${ex.explanation}'`,
    ];
    if (ex.dataTsv) parts.push(`dataTsv: '${ex.dataTsv.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\t/g, '\\t')}'`);
    return `{\n      ${parts.join(',\n      ')},\n    }`;
  });
  const replacement = `[\n    ${body.join(',\n    ')},\n  ]`;
  src = src.slice(0, i) + replacement + src.slice(end + 1);

  if (id === 'amorlinc' || id === 'amordegrc') {
    src = src.replace(
      `patternCn: '=AMORLINC(原值, 买入日, 首期结束, 残值, 期率, 基准)'`,
      `patternCn: '=AMORLINC(原值, 买入日, 首期结束, 残值, 期数, 期率, [基准])'`
    );
    src = src.replace(
      `patternCn: '=AMORDEGRC(原值, 买入日, 首期结束, 残值, 期率, 基准)'`,
      `patternCn: '=AMORDEGRC(原值, 买入日, 首期结束, 残值, 期数, 期率, [基准])'`
    );
    src = src.replace(
      `{ key: 'rate', zh: '期率', en: 'rate', required: false, desc: '折旧率' },`,
      `{ key: 'period', zh: '期数', en: 'period', required: true, desc: '第几个折旧期，从 1 起' },\n    { key: 'rate', zh: '期率', en: 'rate', required: true, desc: '折旧率' },`
    );
  }
  writeFileSync(file, src);
  changed++;
}
console.log(`updated ${changed} samples`);

