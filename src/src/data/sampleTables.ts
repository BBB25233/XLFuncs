import type { CellValue, SampleTableId } from '@/types';

/**
 * 三张统一业务样表（PRD §10.5.1）。
 * 所有示例优先引用这三张表，禁止每个函数自造一套数据 —— 用户看第二个函数时
 * 不用再重新理解一遍示例背景，注意力全在公式上。
 *
 * 数据要真实可信（张三李四王五、华东华南华北、2024 年的日期），禁止 A1/B2 这类占位。
 */

export interface SampleTable {
  id: SampleTableId;
  name: string;
  /** 列名（表头） */
  columns: string[];
  /** 数据行（不含表头） */
  rows: CellValue[][];
  /** 表头左上角所在的单元格，如 'A1'（数据从第 2 行开始） */
  anchor: string;
  /** 一张表的一句话说明 */
  note: string;
}

